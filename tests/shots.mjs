const BASE = "http://127.0.0.1:3100";
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1366, height: 820 } });
const page = await context.newPage();
await page.goto(BASE + "/login"); await page.screenshot({ path: "/tmp/web-shots/a-sign-in.png" });
await page.fill("#email", "sana@example.com"); await page.fill("#password", "password2");
await page.click('button[type="submit"]'); await page.waitForURL("**/search");
await page.goto(BASE + "/search?q=HACCP&exp_from=5&exp_to=12&city=Karachi,%20Lahore&review=reviewed"); await page.waitForLoadState("networkidle");
await page.locator('.row input[type="checkbox"]').nth(0).check(); await page.locator('.row input[type="checkbox"]').nth(2).check();
await page.screenshot({ path: "/tmp/web-shots/b-search-filters.png" });
