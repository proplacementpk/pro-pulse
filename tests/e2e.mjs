// End-to-end checks of the web portal, in a real browser, against the sample-data server
// (tests/seed.py) and a running portal:   BASE=http://127.0.0.1:3100 node tests/e2e.mjs
import { chromium } from "playwright-core";
import { mkdirSync } from "node:fs";

const BASE = process.env.BASE || "http://127.0.0.1:3100";
const SHOTS = process.env.SHOTS || "/tmp/web-shots";
mkdirSync(SHOTS, { recursive: true });
let passed = 0, failed = 0;
const check = (ok, what) => { if (ok) { passed++; console.log("  ok  " + what); } else { failed++; console.log("  FAIL " + what); } };

const browser = await chromium.launch({ executablePath: process.env.CHROME || "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1366, height: 820 }, colorScheme: "light" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error" && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });

const total = async () => Number((await page.getByTestId("total").innerText()).replace(/[^\d]/g, ""));
const names = () => page.locator(".row .name").allInnerTexts();
const go = async (path) => { await page.goto(BASE + path); await page.waitForLoadState("networkidle"); };
const signIn = async (email, password) => {
  await page.fill("#email", email); await page.fill("#password", password);
  await page.click('button[type="submit"]');
};

console.log("Signing in");
await go("/search");
check(page.url().includes("/login") && page.url().includes("next=%2Fsearch"), "a visitor who is not signed in is sent to the sign-in screen");
await page.screenshot({ path: `${SHOTS}/01-sign-in.png` });
await signIn("sana@example.com", "wrong-password");
await page.waitForSelector(".notice.bad");
check((await page.innerText(".notice.bad")).includes("not right") && page.url().includes("/login"), "a wrong password is refused with a plain message");
await signIn("omar@example.com", "password3");
await page.waitForFunction(() => document.querySelector(".notice.bad")?.textContent?.includes("waiting"));
check(true, "an account that is not switched on cannot get in");
for (let i = 0; i < 5; i++) { await signIn("guess@example.com", "nope" + i); await page.waitForTimeout(250); }
await signIn("guess@example.com", "nope-again");
await page.waitForFunction(() => document.querySelector(".notice.bad")?.textContent?.includes("Too many"));
check(true, "after five wrong tries, sign-in is paused for that address");
await signIn("sana@example.com", "password2");
await page.waitForURL("**/search");
check(await total() === 64, "after signing in, Search lists every candidate (64)");
const cookies = await context.cookies();
const session = cookies.find((c) => c.name === "pp_session");
check(session && session.httpOnly && !session.value.includes("eyJ"), "the sign-in cookie is hidden from scripts and encrypted");
check(await page.locator(".who .role").innerText() === "Consultant", "the side bar shows who is signed in");

console.log("Filters");
await page.fill('input[name="exp_from"]', "5"); await page.fill('input[name="exp_to"]', "8");
await page.click("text=Apply filters"); await page.waitForURL(/exp_from=5/);
check(page.url().endsWith("/search?exp_from=5&exp_to=8"), "the address holds only the filters in use: " + page.url().split("/search")[1]);
let years = (await page.locator(".row .facts b").allInnerTexts()).map((t) => parseFloat(t));
check(years.length > 5 && years.every((y) => y >= 5 && y < 9), `experience 5 to 8 lists only people in that range (${await total()} found)`);
check((await page.locator(".chip").first().innerText()).trim() === "5 to 8 years", "the filter in use is shown as a chip");
await go("/search?exp_from=7&exp_to=7");
years = (await page.locator(".row .facts b").allInnerTexts()).map((t) => parseFloat(t));
check(years.length > 0 && years.every((y) => y >= 7 && y < 8) && (await page.locator(".chip").first().innerText()).includes("Exactly 7 years"), "the same number twice means exactly that many years");
await go("/search?exp_from=15");
check((await page.locator(".chip").first().innerText()).includes("15 years or more") && await total() > 0, "only a lower limit means that many years or more");
await go("/search?city=Karachi,%20Lahore&size=100");
const cities = new Set((await page.locator(".row .facts div:last-child").allInnerTexts()).map((t) => t.trim()));
check(cities.size === 2 && cities.has("Karachi") && cities.has("Lahore"), "several cities can be searched at once");
await go("/search?skills=UHT,%20Audits");
const both = await total();
await go("/search?skills=UHT,%20Audits&skills_mode=any");
const either = await total();
check(both === 0 && either > 10, `skills can be all of them (${both}) or any of them (${either})`);
await go("/search?status=Placed&status=Do%20not%20contact&size=100");
const tags = await page.locator(".row .who-line .tag:not(.warn)").allInnerTexts();
check(tags.length === await total() && tags.every((t) => t === "Placed" || t === "Do not contact"), "status filters to the chosen statuses");
await go("/search?in_role=any");
check(await total() === 4, "In at least one role finds the four people who are in roles");
await go("/search?in_role=none");
check(await total() === 60, "Not in any role finds the rest");
await page.selectOption("#f-role", { label: "Plant Manager, Karachi" });
await page.selectOption("#f-in-role", "");
await page.selectOption("#f-stage", { label: "Interview" });
await page.click("text=Apply filters"); await page.waitForURL(/stage=/);
check(await total() === 1 && (await names())[0] === "Ayesha Khan", "role and stage together find who is at Interview in that role");
const yearAgo = new Date(Date.now() - 300 * 864e5).toISOString().slice(0, 10);
await go(`/search?added_to=${yearAgo}`);
check(await total() === 2, "the date-added filter finds the two people added over a year ago");
await go("/search?review=unreviewed&notice=immediate");
check(await total() > 0 && (await page.locator(".tag.warn").count()) === (await page.locator(".row").count()), "review state and notice period combine");
await go("/search?resume=yes");
check(await total() === 2, "Has a resume file finds the two profiles with a file");
await go("/search?q=plant%20manager");
check((await names())[0] === "Ayesha Khan" && (await page.locator('select[name="sort"]').inputValue()) === "match", "a word search puts the best match first");
await page.selectOption('select[name="sort"]', "experience");
await page.waitForURL(/sort=experience/);
years = (await page.locator(".row .facts b").allInnerTexts()).map((t) => parseFloat(t));
check(years.every((y, i) => i === 0 || years[i - 1] >= y), "the list can be ordered by experience");
await go("/search?city=Karachi&exp_from=5&review=reviewed");
check(await page.locator(".chip:not(.clear)").count() === 3 && (await page.locator('.filters-title .count-badge').innerText()) === "3", "three filters in use show three chips and a count");
const before = await total();
await page.locator(".chip", { hasText: "Karachi" }).click(); await page.waitForURL((u) => !u.search.includes("city"));
check(await total() > before && await page.locator(".chip:not(.clear)").count() === 2, "removing a chip widens the search");
await page.click("text=Clear all"); await page.waitForURL("**/search");
check(await total() === 64 && await page.locator(".chip").count() === 0, "Clear all removes every filter");
await page.screenshot({ path: `${SHOTS}/02-search.png` });

console.log("Paging and selection");
await page.selectOption('select[name="size"]', "25"); await page.waitForURL(/size=25/);
check(await page.locator(".row").count() === 25 && (await page.getByTestId("range").innerText()).startsWith("Showing 1 to 25 of 64"), "25 per page shows the first 25 of 64");
const firstPage = await names();
await page.locator('.row input[type="checkbox"]').nth(0).check();
await page.locator('.row input[type="checkbox"]').nth(1).check();
await page.click("text=Next"); await page.waitForURL(/page=2/); await page.waitForLoadState("networkidle");
const secondPage = await names();
check(!secondPage.some((n, i) => n === firstPage[i]) && (await page.getByTestId("range").innerText()).startsWith("Showing 26 to 50"), "the next page shows other candidates");
await page.waitForFunction(() => document.querySelector('[data-testid="selected"]')?.textContent === "2 selected");
check(true, "ticks are kept from page to page");
await page.locator('.row input[type="checkbox"]').nth(0).check();
check(await page.getByTestId("selected").innerText() === "3 selected", "ticks on this page add to the earlier ones");
await page.click("text=Select all 64");
await page.waitForFunction(() => document.querySelector('[data-testid="selected"]')?.textContent === "64 selected");
check(await page.locator(".row.on").count() === 25, "Select all ticks every result on every page");
await page.click("text=Clear selection");
check(await page.locator(".row.on").count() === 0 && await page.getByTestId("selected").count() === 0, "Clear selection unticks everything");
await page.getByLabel("Select everyone on this page").check();
check(await page.getByTestId("selected").innerText() === "25 selected", "Select page ticks the 25 on screen");
await page.getByLabel("Select everyone on this page").uncheck();

console.log("Adding to a role");
await go("/search?q=Zainab");
await page.locator('.row input[type="checkbox"]').first().check();
await page.selectOption('.bar select', { label: "Production Head, Lahore" });
await page.click("text=Add to role");
await page.waitForSelector(".toast");
check((await page.innerText(".toast")).startsWith("Added 1 to Production Head, Lahore"), "the ticked candidate is added to the chosen role");
await page.click("text=Add to role");
await page.waitForFunction(() => document.querySelector(".toast")?.textContent?.includes("already there"));
check(true, "adding again says they are already there");
await go("/search?in_role=any");
check(await total() === 5, "the search now finds five people in roles");

console.log("Candidate profile");
await go("/search?q=Ayesha");
await page.click(".row .name"); await page.waitForURL(/\/candidates\//);
check(await page.innerText("h1") === "Ayesha Khan" && (await page.innerText(".headline")).includes("Plant Manager at Dairy processor"), "a profile opens from the list");
const body = await page.innerText(".main");
check(body.includes("ayesha.khan@example.com") && body.includes("UHT processing") && body.includes("Mar 2019 to Present") && body.includes("PKR 450,000"), "the profile shows contact details, skills, job history and pay");
check(body.includes("Plant Manager, Karachi") && body.includes("Interview") && body.includes("Spoke on the phone"), "it shows the roles, stages and notes");
await page.screenshot({ path: `${SHOTS}/03-profile.png`, fullPage: true });
await page.fill('textarea[name="body"]', "Web note: available from January.");
await page.click("text=Save note");
await page.waitForFunction(() => document.querySelector(".note p")?.textContent?.startsWith("Web note"));
check((await page.locator(".note .by").first().innerText()).startsWith("Sana Malik") && await page.inputValue('textarea[name="body"]') === "", "a note is saved under the person's name and the box is cleared");
await page.selectOption('select[name="role"]', { label: "Area Sales Manager" });
await page.click("text=Add to role");
await page.waitForSelector(".notice.good");
check((await page.locator(".line-list li", { hasText: "Area Sales Manager" }).count()) === 1, "a candidate is added to a role from the profile");
const openLink = await page.locator(".line-list a.btn", { hasText: "Open" }).first().getAttribute("href");
const gone = await context.request.get(BASE + openLink);
const nobody = await fetch(BASE + openLink, { redirect: "manual" });
check(nobody.status !== 200, "the same file address gives nothing to someone who is not signed in");
check(/^\/api\/resumes\/[0-9a-f-]{36}$/.test(openLink || "") && gone.status() === 200 && (await gone.text()).startsWith("%PDF") && gone.headers()["content-type"] === "application/pdf", "a stored file opens through the portal, with no Google sign-in");
await page.click("text=Edit"); await page.waitForURL(/\/edit$/);
await page.fill("#expected_salary", "PKR 520,000"); await page.fill("#skills", "UHT processing, HACCP, ISO 22000, SAP B1, Team leadership, Budgeting");
await page.fill("#total_experience_years", "99"); await page.click("text=Save changes");
await page.waitForTimeout(400);
check(page.url().endsWith("/edit") && await page.locator("#total_experience_years:invalid").count() === 1, "a number of years that cannot be right is not accepted");
await page.fill("#total_experience_years", "12"); await page.click("text=Save changes");
await page.waitForURL(/saved=1/);
const after = await page.innerText(".main");
check(after.includes("PKR 520,000") && after.includes("Budgeting") && after.includes("12 years") && after.includes("Changes saved"), "edits are saved and shown");
await go("/search?review=unreviewed");
await page.click(".row .name"); await page.waitForURL(/\/candidates\//);
await page.click("text=Mark reviewed"); await page.waitForFunction(() => !document.body.innerText.includes("Mark reviewed"));
check(await page.locator(".tag.warn").count() === 0, "Mark reviewed clears the Unreviewed flag");
await go("/candidates/00000000-0000-0000-0000-000000000000");
check((await page.innerText(".main")).includes("That page is not here"), "a profile that does not exist says so");

console.log("Look, small screens and signing out");
await go("/search?q=HACCP&city=Karachi");
await page.click('button[title="Switch between light and dark"]');
check(await page.evaluate(() => document.documentElement.dataset.theme) === "dark", "the theme button switches to dark");
await page.screenshot({ path: `${SHOTS}/04-search-dark.png` });
await page.reload(); await page.waitForLoadState("networkidle");
check(await page.evaluate(() => document.documentElement.dataset.theme) === "dark", "the theme choice is remembered");
await page.click('button[title="Switch between light and dark"]');
await page.setViewportSize({ width: 390, height: 800 });
await go("/search?q=HACCP");
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
check(overflow <= 1, `on a phone nothing runs off the side of the screen (${overflow}px)`);
check(!(await page.locator(".filters").isVisible()) && await page.locator(".row").first().isVisible(), "on a phone the results come first and the filters open from a button");
await page.screenshot({ path: `${SHOTS}/05-phone-search.png` });
await page.click(".filter-toggle");
check(await page.locator("#f-city").isVisible(), "the Filters button opens the filters");
await page.click(".filter-toggle");
await page.click(".row .name"); await page.waitForURL(/\/candidates\//);
check(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth) <= 1, "the profile fits a phone too");
await page.screenshot({ path: `${SHOTS}/06-phone-profile.png` });
await page.setViewportSize({ width: 1366, height: 820 });
await page.click('button[title="Sign out of the portal on this device"]');
await page.waitForURL("**/login");
await go("/search");
check(page.url().includes("/login") && !(await context.cookies()).some((c) => c.name === "pp_session"), "signing out ends the session");
check(errors.length === 0, "no errors in the browser (" + errors.slice(0, 2).join(" | ") + ")");

await browser.close();
console.log(failed ? `\n${failed} CHECK(S) FAILED, ${passed} passed` : `\nALL ${passed} WEB CHECKS PASSED`);
process.exit(failed ? 1 : 0);
